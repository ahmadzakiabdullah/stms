const dictionaries: Record<string, Translations> = { en, ms };

export function translate(locale: string, key: string): string {
    return dictionaries[locale]?.[key] ?? dictionaries.en[key] ?? key;
}

export function localeTag(locale: string): string {
    return locale === 'ms' ? 'ms-MY' : 'en-MY';
}

export function formatDate(value: string | Date | null | undefined, locale: string): string {
    if (!value) {
        return translate(locale, 'Date not set');
    }

    return new Intl.DateTimeFormat(localeTag(locale), {
        day: 'numeric',
        month: 'short',
        year: 'numeric',
    }).format(value instanceof Date ? value : new Date(value));
}

export function formatDateTime(value: string | Date | null | undefined, locale: string): string {
    if (!value) {
        return translate(locale, 'Time TBD');
    }

    return new Intl.DateTimeFormat(localeTag(locale), {
        dateStyle: 'medium',
        timeStyle: 'short',
    }).format(value instanceof Date ? value : new Date(value));
}

export function formatNumber(value: number, locale: string): string {
    return new Intl.NumberFormat(localeTag(locale)).format(value);
}

export function useI18n() {
    const { locale = 'en' } = usePage<PageProps>().props;
    return {
        locale,
        t: (key: string) => translate(locale, key),
    };
}
